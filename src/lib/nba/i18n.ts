export const dictionaries: Record<Lang, Record<Key, string>> = { en, fr, es, tr, ar, zh };

export function t(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? dictionaries.en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function localeFor(lang: Lang): string {
  if (lang === "fr") return "fr-FR";
  if (lang === "es") return "es-ES";
  if (lang === "tr") return "tr-TR";
  if (lang === "ar") return "ar-EG-u-nu-latn";
  if (lang === "zh") return "zh-CN";
  return "en-US";
}

export function dirFor(lang: Lang): "rtl" | "ltr" {
  return lang === "ar" ? "rtl" : "ltr";
}

export function phaseLabel(phase: string, lang: Lang): string {
  const value = phase.toLowerCase();
  if (value.includes("post")) return t(lang, "postseason");
  if (value.includes("preseason") || value.includes("pre-season")) return t(lang, "preseason");
  if (value.includes("off")) return t(lang, "offseason");
  if (value.includes("regular") || value === "reg") return t(lang, "regular");
  return phase;
}

export function statusKey(status: string, rawName: string): Key {
  const raw = rawName.toUpperCase();
  if (raw.includes("HALF")) return "halftime";
  if (status === "post") return "final";
  if (status === "in") return "live";
  if (status === "postponed") return "postponed";
  if (status === "canceled") return "canceled";
  if (status === "delayed") return "delayed";
  return "scheduled";
}

export function injuryStatus(lang: Lang, raw: string): string {
  const value = raw.toLowerCase();
  if (value === "out") return t(lang, "stOut");
  if (value.includes("day")) return t(lang, "stDtd");
  if (value.startsWith("question")) return t(lang, "stQ");
  if (value.startsWith("prob")) return t(lang, "stProb");
  if (value.startsWith("doubt")) return t(lang, "stDoubt");
  return raw;
}
